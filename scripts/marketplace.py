#!/usr/bin/env python3
"""Generate the Claude Code plugin marketplace from ecosystem.json.

Writes two files, both generated (edit ecosystem.json, not them):
  .claude-plugin/marketplace.json                       one entry per component with "plugin": true (a github
                                                        source, no version, so installs track each repository's
                                                        commits unless its own plugin.json pins a version),
                                                        plus the meta plugin below
  plugins/video-production-os/.claude-plugin/plugin.json the meta plugin: depends on every non-optional plugin,
                                                        so installing it installs the whole OS; its own skill
                                                        (skills/video-production-os/SKILL.md, hand-written)
                                                        says which skill to use for what; its "who owns
                                                        what" table is regenerated here too

Usage:
  python3 scripts/marketplace.py           write both files
  python3 scripts/marketplace.py --check   exit 1 if either file is not what ecosystem.json produces
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[1]
MARKETPLACE_NAME = "ai-video-production-os"
META = "video-production-os"
META_DIR = f"plugins/{META}"


def build(manifest: Dict[str, Any]) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    org = manifest["org"]
    departments = {d["id"]: d for d in manifest["departments"]}
    plugins = [c for c in manifest["components"] if c.get("plugin") and c.get("status") != "planned"]
    entries: List[Dict[str, Any]] = [{
        "name": META,
        "source": f"./{META_DIR}",
        "description": "Installs the whole AI Video Production OS: every Skill below except the optional disc-authoring kits, and the routing skill that picks the right one.",
        "category": "os",
    }]
    for c in plugins:
        dep = departments[c["department"]]
        entries.append({
            "name": c["repo"],
            "source": {"source": "github", "repo": f"{org}/{c['repo']}"},
            "description": c["role"],
            "category": dep["en"].lower(),
            "tags": [dep["en"].lower(), dep["name"]] + (["optional"] if c.get("optional") else []) + (["scaffold"] if c["status"] == "scaffold" else []),
        })
    marketplace = {
        "name": MARKETPLACE_NAME,
        "description": "AI Video Production OS: production skills for video, audio, subtitles, QC and delivery, and the agent that plans with them.",
        "owner": {"name": org, "url": f"https://github.com/{org}"},
        "plugins": entries,
    }
    meta = {
        "name": META,
        "displayName": "AI Video Production OS",
        "description": "The whole AI Video Production OS in one install: the production agent and every Skill, plus the routing skill that prefers them and falls back honestly when one is missing.",
        "author": {"name": org, "url": f"https://github.com/{org}"},
        "homepage": f"https://github.com/{org}/Velisa",
        "repository": f"https://github.com/{org}/Velisa",
        "keywords": ["video", "audio", "ffmpeg", "production"],
        "dependencies": [c["repo"] for c in plugins if not c.get("optional")],
    }
    return marketplace, meta


BEGIN, END = "<!-- BEGIN generated by scripts/marketplace.py from ecosystem.json -->", "<!-- END generated -->"


def owner_table(manifest: Dict[str, Any], skill_text: str) -> str:
    """The routing skill with its "who owns what" block regenerated: every non-planned component, plugin or not
    (a repository without a skill is still the owner of its job, reached through its CLI or the agent)."""
    departments = {d["id"]: d for d in manifest["departments"]}
    rows = ["| Skill | Department | Owns |", "|---|---|---|"]
    for c in manifest["components"]:
        if c.get("status") == "planned":
            continue
        note = " (optional)" if c.get("optional") else (" (scaffold)" if c["status"] == "scaffold" else "")
        how = "" if c.get("plugin") else " -- CLI only, no skill yet"
        rows.append(f"| `{c['repo']}`{note}{how} | {departments[c['department']]['name']} | {', '.join(c['owns'])} |")
    head, rest = skill_text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + BEGIN + "\n" + "\n".join(rows) + "\n" + END + tail


def render(doc: Dict[str, Any]) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    a = ap.parse_args(argv)
    manifest = json.loads((ROOT / "ecosystem.json").read_text(encoding="utf-8"))
    marketplace, meta = build(manifest)
    skill = ROOT / META_DIR / "skills" / META / "SKILL.md"
    targets = [(ROOT / ".claude-plugin" / "marketplace.json", render(marketplace)),
               (ROOT / META_DIR / ".claude-plugin" / "plugin.json", render(meta)),
               (skill, owner_table(manifest, skill.read_text(encoding="utf-8")))]
    stale = [p for p, text in targets if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python3 scripts/marketplace.py)")
        return 1 if stale else 0
    for p, text in targets:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
